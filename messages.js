/**
 * MessageEngine manages non-repeating message randomization with a recent-exclusion list
 * and shuffle-bag behavior.
 */
export class MessageEngine {
  constructor(messages = INSPIRATIONAL_MESSAGES, maxRecent = 25) {
    this.messages = messages;
    this.maxRecent = Math.min(maxRecent, Math.floor(messages.length / 2));
    this.recentIds = [];
    this.currentMessage = null;
    this.timer = null;
  }

  getRandomMessage() {
    // Exclude recently shown messages
    const candidates = this.messages.filter(m => !this.recentIds.includes(m.id));
    const pool = candidates.length > 0 ? candidates : this.messages;
    
    // Pick random
    const idx = Math.floor(Math.random() * pool.length);
    const selected = pool[idx];

    // Track in recent list
    this.recentIds.push(selected.id);
    if (this.recentIds.length > this.maxRecent) {
      this.recentIds.shift();
    }

    this.currentMessage = selected;
    return selected;
  }

  getCurrentMessage() {
    if (!this.currentMessage) {
      return this.getRandomMessage();
    }
    return this.currentMessage;
  }
}

export const messageEngine = new MessageEngine();

